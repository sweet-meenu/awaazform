let current = 'en';

export const getLang = () => current;

export function setLang(code) {
  current = DICT[code] ? code : 'en';
  document.documentElement.lang = current;
}

export function t(key, ...args) {
  let s = DICT[current][key] ?? DICT.en[key] ?? key;
  args.forEach((a, i) => { s = s.replace(`{${i}}`, a); });
  return s;
}

// Fill every element that has data-i18n / data-i18n-label / data-lang-btn.
export function applyStatic() {
  document.documentElement.lang = current;
  document.querySelectorAll('[data-i18n-placeholder]').forEach((n) => {
    n.setAttribute('placeholder', t(n.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n]').forEach((n) => {
    n.textContent = t(n.dataset.i18n);
  });
  document.querySelectorAll('[data-lang-btn]').forEach((b) => {
    b.setAttribute('aria-pressed', String(b.dataset.langBtn === current));
  });
}
