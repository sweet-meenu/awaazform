// Writes backend/app/contract.json from packages/core: the system prompt for each language, language
// names and the model's tool declarations. TypeScript stays the single source; the Python API reads this,
// so the two can't drift. Run after changing prompts.ts or tools.ts: node scripts/export-contract.mjs
import { createRequire } from 'node:module';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'apps/extension/package.json'));
const esbuild = require('esbuild');

const tmp = mkdtempSync(join(tmpdir(), 'awaaz-contract-'));
const out = join(tmp, 'contract.mjs');
await esbuild.build({
  stdin: {
    contents: `export { systemPrompt, LANGUAGE_NAMES, LANGUAGES, toolDeclarations } from './packages/core/src/index.ts';`,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error',
});
const core = await import(pathToFileURL(out).href);
rmSync(tmp, { recursive: true, force: true });

// Placeholders the backend fills in (it never trusts the client with the prompt itself).
const FT = '{{formTitle}}', PL = '{{profileLabel}}';
const contract = {
  _note: 'Generated by scripts/export-contract.mjs from packages/core. Do not edit by hand.',
  languages: [...core.LANGUAGES],
  languageNames: core.LANGUAGE_NAMES,
  systemPrompts: Object.fromEntries(core.LANGUAGES.map((l) => [l, core.systemPrompt({ formTitle: FT, profileLabel: PL, language: l })])),
  tools: core.toolDeclarations(),
};
writeFileSync(join(root, 'backend/app/contract.json'), JSON.stringify(contract, null, 2) + '\n');
console.log(`contract.json: ${contract.languages.length} languages, ${contract.tools.length} tools`);
